#!/usr/bin/env python3
"""Generates the desktop app icon from the Android launcher icon.

The source is the adaptive launcher icon in branding/src/main/res/drawable
(ic_launcher_background.xml under ic_launcher_foreground.xml). This script
converts those vector drawables to desktopApp/icons/cadence.svg, then
rasterizes that SVG for jpackage (Compose Desktop nativeDistributions):

  desktopApp/src/jvmMain/resources/cadence.png  512px: the Linux icon and the window icon
  desktopApp/icons/cadence.ico                  Windows
  desktopApp/icons/cadence.icns                 macOS

Re-run it after changing the launcher icon, and never hand-edit the output.
Needs rsvg-convert (librsvg) and Pillow.

  scripts/generate-desktop-icons.py
"""

import io
import os
import subprocess
import xml.etree.ElementTree as ET

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DRAWABLES = os.path.join(ROOT, "branding/src/main/res/drawable")
ICONS = os.path.join(ROOT, "desktopApp/icons")
RESOURCES = os.path.join(ROOT, "desktopApp/src/jvmMain/resources")  # ships in the jar

ANDROID = "{http://schemas.android.com/apk/res/android}"
HEADER = "<!-- Generated by scripts/generate-desktop-icons.py; edit the script or the launcher icon, not this file. -->"

# An adaptive icon is 108dp, and launchers show the middle 72dp.
VISIBLE_LO, VISIBLE = 18, 72
# Inset the tile on its canvas the way macOS's icon grid insets its 824px tile on 1024px, so the
# mark sits at the same size as other apps' icons on every desktop.
INSET = VISIBLE * 100 / 824
# Corner radius of the rounded-square tile, in the same proportion as macOS's (185px of 824px).
CORNER = VISIBLE * 185 / 824


def color(value):
  """Converts an Android #AARRGGBB or #RRGGBB color to an SVG color and opacity."""
  hex_ = value.lstrip("#")
  if len(hex_) == 8:
    alpha, rgb = int(hex_[:2], 16) / 255, hex_[2:]
  elif len(hex_) == 6:
    alpha, rgb = 1.0, hex_
  else:
    raise ValueError(f"unsupported color {value}")
  return f"#{rgb}", alpha


def num(value):
  return f"{value:.4f}".rstrip("0").rstrip(".")


def svg_path(el):
  attrs = {"d": el.get(f"{ANDROID}pathData")}
  fill = el.get(f"{ANDROID}fillColor")
  if fill:
    rgb, alpha = color(fill)
    attrs["fill"] = rgb if alpha else "none"
    if 0 < alpha < 1:
      attrs["fill-opacity"] = num(alpha)
  else:
    attrs["fill"] = "none"
  stroke = el.get(f"{ANDROID}strokeColor")
  if stroke:
    rgb, alpha = color(stroke)
    if alpha:
      attrs["stroke"] = rgb
      if alpha < 1:
        attrs["stroke-opacity"] = num(alpha)
      attrs["stroke-width"] = el.get(f"{ANDROID}strokeWidth", "0")
      for android, svg in (("strokeLineCap", "stroke-linecap"), ("strokeLineJoin", "stroke-linejoin")):
        if el.get(f"{ANDROID}{android}"):
          attrs[svg] = el.get(f"{ANDROID}{android}")
  for key in el.attrib:
    if key.removeprefix(ANDROID) not in (
      "pathData", "fillColor", "strokeColor", "strokeWidth", "strokeLineCap", "strokeLineJoin",
    ):
      raise ValueError(f"unsupported vector drawable attribute {key}")
  return "<path " + " ".join(f'{k}="{v}"' for k, v in attrs.items()) + "/>"


def drawable_paths(name):
  root = ET.parse(os.path.join(DRAWABLES, f"{name}.xml")).getroot()
  if root.get(f"{ANDROID}viewportWidth") != "108" or root.get(f"{ANDROID}viewportHeight") != "108":
    raise ValueError(f"{name} is not a 108x108 adaptive icon layer")
  paths = []
  for el in root:
    if el.tag != "path":
      raise ValueError(f"unsupported element <{el.tag}> in {name}")
    paths.append(svg_path(el))
  return "".join(paths)


def desktop_svg():
  lo, span = VISIBLE_LO - INSET, VISIBLE + 2 * INSET
  body = drawable_paths("ic_launcher_background") + drawable_paths("ic_launcher_foreground")
  return (
    f"{HEADER}\n"
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{num(lo)} {num(lo)} {num(span)} {num(span)}"'
    ' width="1024" height="1024">'
    f'<clipPath id="tile"><rect x="{VISIBLE_LO}" y="{VISIBLE_LO}" width="{VISIBLE}" height="{VISIBLE}"'
    f' rx="{num(CORNER)}"/></clipPath>'
    f'<g clip-path="url(#tile)">{body}</g>'
    "</svg>\n"
  )


def rasterize(svg, size):
  png = subprocess.run(
    ["rsvg-convert", "-w", str(size), "-h", str(size), svg],
    check=True,
    capture_output=True,
  ).stdout
  return Image.open(io.BytesIO(png)).convert("RGBA")


def main():
  os.makedirs(ICONS, exist_ok=True)
  os.makedirs(RESOURCES, exist_ok=True)
  svg = os.path.join(ICONS, "cadence.svg")
  with open(svg, "w") as out:
    out.write(desktop_svg())

  rasterize(svg, 512).save(os.path.join(RESOURCES, "cadence.png"), optimize=True)
  big = rasterize(svg, 1024)
  big.save(
    os.path.join(ICONS, "cadence.ico"), sizes=[(s, s) for s in (16, 24, 32, 48, 64, 128, 256)]
  )
  big.save(os.path.join(ICONS, "cadence.icns"))
  print(f"Wrote {svg}, {ICONS}/cadence.{{ico,icns}} and {RESOURCES}/cadence.png")


if __name__ == "__main__":
  main()
